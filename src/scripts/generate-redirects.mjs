/**
 * Generates the deployable redirect rules from the `redirects` map in
 * astro.config.mjs:
 *
 *   ops/nginx/handmadepastaflorence-redirects.conf — real 301s, served by the origin
 *
 * WHY: Astro's static build writes redirects as HTML stubs — a meta-refresh
 * plus `noindex` plus a canonical — which answer HTTP 200, not 301. That
 * combination is worse than it looks: `noindex` and `rel=canonical` contradict
 * each other, so Google is liable to simply drop the old URL rather than pass
 * its accumulated signals to the target. For the merged pasta guide that is
 * 357 impressions and 13 clicks (GSC, 19 Aug – 5 Sep 2026) thrown away instead
 * of consolidated.
 *
 * WHY NGINX AND NOT CLOUDFLARE: both handmadepastaflorence.com and
 * visitkruja.com use Cloudflare *nameservers*, but neither is proxied — apex
 * and www both resolve to the origin (144.91.101.152) and every response is
 * `Server: nginx/1.24.0` with no `cf-ray`. Cloudflare never sees the request,
 * so Redirect Rules and Bulk Redirects cannot fire. visitkruja lost five weeks
 * to exactly this assumption; see that repo's ops/nginx/README.md.
 *
 * Run: node src/scripts/generate-redirects.mjs  (also runs on `npm run build`)
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

import config from '../../astro.config.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, '..', '..', 'ops', 'nginx');
const outFile = join(outDir, 'handmadepastaflorence-redirects.conf');

const redirects = config.redirects ?? {};
const rules = Object.entries(redirects)
  .map(([from, to]) => [from, typeof to === 'string' ? to : to.destination])
  .sort(([a], [b]) => a.localeCompare(b));

const header = `# GENERATED by src/scripts/generate-redirects.mjs — do not edit by hand.
# Source of truth: the \`redirects\` map in astro.config.mjs.
#
# Install: copy to the server and add
#   include /etc/nginx/snippets/handmadepastaflorence-redirects.conf;
# inside the \`server { ... }\` block for handmadepastaflorence.com, then
#   nginx -t && systemctl reload nginx
#
# Without this file the static build's meta-refresh stubs answer 200 and carry
# \`noindex\`, so Google drops the old URLs instead of consolidating them onto
# the new ones. See the header comment in the generator for the full reasoning.
#
# NOTE: Cloudflare Redirect Rules are NOT an alternative here — the domain uses
# Cloudflare DNS only (grey cloud) and traffic goes straight to this origin.
`;

const body = rules
  .map(([from, to]) => `location = ${from} { return 301 ${to}$is_args$args; }`)
  .join('\n');

mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, `${header}\n${body}\n`, 'utf8');
console.log(`[redirects] wrote ${rules.length} rule(s) to ops/nginx/handmadepastaflorence-redirects.conf`);
